#include <iostream>
using namespace std;

int main() {
    // Массив из 7 целых чисел (как в домашнем задании)
    int arr[7] = {5, 2, 8, 1, 9, 4, 7}; 
    int n = 7;

    cout << "Исходный массив: ";
    for (int i = 0; i < n; i++) cout << arr[i] << " ";
    cout << "\n\n";

    // Внешний цикл (Шаг 4): начинаем со второго элемента (индекс 1)
    for (int i = 1; i < n; i++) {
        int y = arr[i]; // Очередной элемент (Шаг 5)
        int j = i - 1;  // Индекс для левой (отсортированной) части
        
        bool F = false; // Флажок (Шаг 6)

        // Внутренний цикл (Шаг 4): ищем место для вставки
        while (j >= 0 && !F) { 
            if (arr[j] > y) {
                // Если элемент больше y, сдвигаем его вправо
                arr[j + 1] = arr[j];
                j = j - 1;
            } else {
                // Если нашли элемент меньше или равный y, 
                // значит место найдено, поднимаем флажок
                F = true; 
            }
        }
        
        // Вставляем y на освободившееся место
        // (если F = true, то j указывает на элемент меньше y, ставим после него)
        // (если F = false, значит дошли до начала, j стал -1, ставим в 0-ю ячейку)
        arr[j + 1] = y; 

        // Вывод массива после каждого прохода (для рисунков)
        cout << "Шаг " << i << ": ";
        for (int k = 0; k < n; k++) cout << arr[k] << " ";
        cout << endl;
    }

    return 0;
}